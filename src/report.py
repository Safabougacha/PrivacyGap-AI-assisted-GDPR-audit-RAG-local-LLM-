"""Step 4 - Turn the audit results into a readable Markdown report."""
from datetime import date

from src.schemas import FlowResult

ICON = {"high": "🔴 High", "medium": "🟠 Medium", "low": "🟢 Low"}


def to_markdown(case: str, results: list[FlowResult], model: str) -> str:
    count = {lvl: sum(r.risk_level == lvl for r in results) for lvl in ICON}
    review = [r.flow_id for r in results if r.needs_human_review]
    lines = [
        f"# Privacy audit report — {case}",
        "",
        f"*Generated by PrivacyGap on {date.today()} (LLM: `{model}`). Audit-support tool: "
        "findings must be reviewed by a privacy professional.*",
        "",
        "## Summary",
        "",
        f"- **{len(results)} data flows audited**",
        f"- **{sum(r.contradicts_policy for r in results)}** contradict the privacy policy",
        f"- Risk: {count['high']} high · {count['medium']} medium · {count['low']} low",
        f"- Flows needing human review (rule and LLM disagree on the data type): "
        f"{', '.join(review) or 'none'}",
        "",
        "| Flow | Data | Recipient | Contradiction | Risk | GDPR articles |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in results:
        lines.append(
            f"| {r.flow_id} | {r.flow['data_fields']} | {r.flow['recipient']} | "
            f"{'Yes (' + r.policy_reference + ')' if r.contradicts_policy else 'No'} | "
            f"{ICON[r.risk_level]} | {', '.join(map(str, r.cited_articles)) or '—'} |")
    lines += ["", "## Findings", ""]
    for r in results:
        lines += [
            f"### {r.flow_id} — {r.flow['event_name']}",
            "",
            f"- **Flow:** {r.flow['data_fields']} → **{r.flow['recipient']}** "
            f"({r.flow['recipient_type']}), purpose: {r.flow['purpose']}, consent: {r.flow['consent']}",
            f"- **Data type:** {r.special_reason}"
            f"{' — ⚠️ the LLM disagrees, human review needed' if r.needs_human_review else ''}",
            f"- **Privacy policy:** {'contradicted (' + r.policy_reference + ')' if r.contradicts_policy else 'not contradicted'}"
            f" — {r.policy_explanation}",
            f"- **Risk:** {ICON[r.risk_level]} — because {'; '.join(r.risk_reasons)}",
            f"- **Justification:** {r.justification}",
            f"- **Recommendation:** {r.recommendation}",
            f"- **GDPR articles:** {', '.join(map(str, r.cited_articles)) or '—'}",
        ]
        if r.retrieval_misses:
            lines.append(f"- ⚠️ **Articles not found by the search (check manually):** "
                         f"{', '.join(map(str, r.retrieval_misses))}")
        lines += [f"- *Source of the flow:* {r.flow.get('source', '')}", ""]
    return "\n".join(lines)
